export const DAY0 = Date.UTC(1934, 9, 10);
export const DAY_END = Date.UTC(1936, 10, 22);
export const dayOf = (s: string): number => Math.round((Date.parse(s + 'T00:00:00Z') - DAY0) / 86400000);
export const dateOf = (d: number): Date => new Date(DAY0 + d * 86400000);
export const fmtDate = (d: number): string => {
  const t = dateOf(d);
  return `${t.getUTCFullYear()}年${t.getUTCMonth() + 1}月${t.getUTCDate()}日`;
};

